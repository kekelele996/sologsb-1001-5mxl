export type MessageKey = keyof (typeof messages)['zh-CN']

export const translate = (locale: Locale, key: MessageKey, values: Record<string, string | number> = {}) => {
  const template = messages[locale][key] ?? messages['zh-CN'][key] ?? key
  return Object.entries(values).reduce<string>((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template)
}
